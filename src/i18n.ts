const DICTS: Record<LangCode, Dict> = {
  en,
  ja,
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  ko,
  es,
  fr,
  de,
};

export function tr(lang: LangCode, key: MessageKey): string {
  return (DICTS[lang] ?? en)[key] ?? en[key];
}

/**
 * Map a locale string (e.g. "ja", "zh-TW", "en-US") to a supported language.
 * Only the first non-empty candidate is used, so an unsupported Obsidian language
 * falls back to English instead of being overridden by a later candidate.
 */
export function detectLanguage(...candidates: (string | null | undefined)[]): LangCode {
  for (const c of candidates) {
    if (!c) continue;
    const l = c.toLowerCase().replace(/_/g, "-");
    if (l.startsWith("zh")) {
      return /^zh-(tw|hk|mo|hant)/.test(l) ? "zh-TW" : "zh-CN";
    }
    const base = l.split("-")[0];
    return isLangCode(base) ? base : "en";
  }
  return "en";
}
